import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as v from 'valibot';
import yaml from 'yaml';
import { EventCardSchema, LifeTableDecadeSchema, LocationSchema } from './schema.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rawDir = path.resolve(__dirname, '../raw');
const outDir = path.resolve(__dirname, '../dist');

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

function loadAndValidate<T>(
  filePath: string,
  schema: v.BaseSchema<unknown, T, v.BaseIssue<unknown>>,
): T[] {
  console.log(`[compile] Validating ${path.basename(filePath)}...`);
  const content = fs.readFileSync(filePath, 'utf8');
  const parsed = yaml.parse(content);
  if (!Array.isArray(parsed)) {
    throw new Error(`Expected array in ${filePath}`);
  }
  return parsed.map((item, index) => {
    try {
      return v.parse(schema, item);
    } catch (err) {
      console.error(`Validation failed at index ${index} in ${filePath}`);
      throw err;
    }
  });
}

const locations = loadAndValidate(path.join(rawDir, 'locations.yaml'), LocationSchema);
const lifeTables = loadAndValidate(path.join(rawDir, 'life_tables.yaml'), LifeTableDecadeSchema);
const events = loadAndValidate(path.join(rawDir, 'events.yaml'), EventCardSchema);

const compiledData = {
  version: '0.1.0',
  buildTimestamp: new Date().toISOString(),
  locations,
  lifeTables,
  events,
};

const jsonPath = path.join(outDir, 'era-data.json');
fs.writeFileSync(jsonPath, JSON.stringify(compiledData, null, 2), 'utf8');
console.log(`[compile] Wrote ${jsonPath} (${(fs.statSync(jsonPath).size / 1024).toFixed(2)} KB)`);

const tsPath = path.join(outDir, 'index.ts');
const tsContent = `// Auto-generated by @era/data compile script. Do not edit directly.
import data from './era-data.json';
export const compiledData = data;
export default data;
`;
fs.writeFileSync(tsPath, tsContent, 'utf8');
console.log(`[compile] Compilation completed successfully.`);
